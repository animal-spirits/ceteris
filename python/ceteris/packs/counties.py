"""County display layer from geoBoundaries gbOpen (ADR 0009).

`counties.lock.toml` pins one boundary file per country. Regenerate it deliberately with

    uv run python -m ceteris.packs.counties --record

which queries the geoBoundaries metadata API, chooses a level per country, downloads the files
and writes their checksums and licences.
"""

import argparse
import collections
import json
import tomllib
import urllib.request
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pyogrio
import shapely
from shapely import STRtree

from . import fetch, geo

LOCK = Path(__file__).with_name("counties.lock.toml")
API = "https://www.geoboundaries.org/api/current/gbOpen/ALL/{level}/"
LEVELS = ("ADM2", "ADM3")
# Units per Natural Earth province: prefer the coarsest level in [GOOD, MAX], else [MIN, GOOD).
MIN_RATIO, GOOD_RATIO, MAX_RATIO = 1.5, 3.0, 120.0
# Canada's ADM3 (5,162 census subdivisions) is municipal; its census divisions are the county level.
# Brazil has no open level between states and its 5,570 municipalities, which exceed MAX_RATIO.
OVERRIDES = {"BRA": "ADM2", "CAN": "ADM2"}


def choose_level(units: dict[str, int], provinces: int, override: str | None = None) -> str | None:
    if override:
        return override if override in units else None
    ratios = [(level, units[level] / provinces) for level in LEVELS if level in units]
    for lo, hi in ((GOOD_RATIO, MAX_RATIO), (MIN_RATIO, GOOD_RATIO)):
        for level, r in ratios:
            if lo <= r <= hi:
                return level
    return None


def entries() -> list[dict]:
    """Lock entries in the shape of `fetch.toml` files."""
    if not LOCK.exists():
        return []
    return [
        {"source": "geoboundaries", "name": f"geoboundaries/{c['iso']}-{c['level']}.geojson", **c}
        for c in tomllib.loads(LOCK.read_text())["country"]
    ]


@dataclass
class County:
    iso: str
    level: str
    name: str
    geom: shapely.Geometry
    lon: float = 0.0
    lat: float = 0.0


def load(cache: Path) -> list[County]:
    out = []
    for e in entries():
        meta, t = pyogrio.read_arrow(cache / e["name"], columns=["shapeName"])
        geoms = shapely.from_wkb(t.column(meta["geometry_name"] or "wkb_geometry").to_numpy(zero_copy_only=False))
        for name, g in zip(t.column("shapeName").to_pylist(), geoms):
            g = geo.polygonal(shapely.make_valid(g))
            if not g.is_empty:
                out.append(County(e["iso"], e["level"], name or "", g))
    for c in out:
        c.lon, c.lat = geo.anchor(c.geom)
    return out


def assign(counties: list[County], geoms: list[shapely.Geometry], countries: list[set[str]]) -> np.ndarray:
    """Province index each county overlaps most among provinces of its country, or -1.

    `countries[j]` holds the codes province j answers to (current and 2000), so Crimea's units,
    Ukrainian in geoBoundaries, still find Crimea.
    """
    cg = np.array([c.geom for c in counties], dtype=object)
    pg = np.array(geoms, dtype=object)
    ci, pj = STRtree(pg).query(cg, predicate="intersects")
    keep = np.array([counties[c].iso in countries[p] for c, p in zip(ci, pj)], dtype=bool)
    ci, pj = ci[keep], pj[keep]
    area = shapely.area(shapely.intersection(cg[ci], pg[pj]))
    best = np.full(len(counties), -1)
    best_area = np.zeros(len(counties))
    for c, p, a in zip(ci, pj, area):
        if a > best_area[c] or (a == best_area[c] and best[c] >= 0 and p < best[c]):
            best[c], best_area[c] = p, a
    return best


def record() -> None:
    from .provinces import BORDERS

    meta = {level: {r["boundaryISO"]: r for r in _get_json(API.format(level=level))} for level in LEVELS}
    admin1 = fetch.CACHE / "ne_10m_admin_1_states_provinces.zip"
    _, t = pyogrio.read_arrow(admin1, columns=["adm0_a3"], read_geometry=False)
    per_country = collections.Counter(c for c in t.column("adm0_a3").to_pylist() if c not in BORDERS["exclude"]["countries"])
    lines = [
        "# Generated by `python -m ceteris.packs.counties --record` (ADR 0009). One geoBoundaries gbOpen",
        "# file per country at the level choose_level picks; licences are per file.",
        "",
    ]
    for iso, n in sorted(per_country.items()):
        units = {level: int(meta[level][iso]["admUnitCount"]) for level in LEVELS if iso in meta[level]}
        level = choose_level(units, n, OVERRIDES.get(iso))
        if level is None:
            continue
        r = meta[level][iso]
        e = {"name": f"geoboundaries/{iso}-{level}.geojson", "url": r["simplifiedGeometryGeoJSON"]}
        path = fetch.fetch(e)
        lines += [
            "[[country]]",
            f'iso = "{iso}"',
            f'level = "{level}"',
            f"units = {units[level]}",
            f'year = "{r["boundaryYearRepresented"]}"',
            f"licence = {json.dumps(r['boundaryLicense'])}",
            f'boundary_id = "{r["boundaryID"]}"',
            f'url = "{e["url"]}"',
            f'sha256 = "{fetch.sha256(path)}"',
            f"bytes = {path.stat().st_size}",
            "",
        ]
    LOCK.write_text("\n".join(lines))


def _get_json(url: str):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "ceteris-packs"}), timeout=120) as r:
        return json.load(r)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--record", action="store_true", required=True)
    parser.parse_args()
    record()
