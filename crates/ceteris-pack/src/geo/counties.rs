//! County display layer from geoBoundaries gbOpen (ADR 0009).
//!
//! `counties.lock.toml` pins one boundary file per country. Regenerate it deliberately with
//! `ceteris pack record-counties`, which queries the geoBoundaries metadata API, chooses a level
//! per country, downloads the files and writes their checksums and licences.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde_json::Value;

use crate::fetch::{self, Entry, digest};
use crate::read::natural_earth::Dbf;
use crate::sources::{CONFIG_DIR, read_table};

pub const LOCK: &str = "counties.lock.toml";
const API: &str = "https://www.geoboundaries.org/api/current/gbOpen/ALL/{level}/";
pub const LEVELS: [&str; 2] = ["ADM2", "ADM3"];
// Units per Natural Earth province: prefer the coarsest level in [GOOD, MAX], else [MIN, GOOD).
const MIN_RATIO: f64 = 1.5;
const GOOD_RATIO: f64 = 3.0;
const MAX_RATIO: f64 = 120.0;
/// Canada's ADM3 (5,162 census subdivisions) is municipal; its census divisions are the county
/// level. Brazil has no open level between states and its 5,570 municipalities, which exceed
/// MAX_RATIO.
pub const OVERRIDES: [(&str, &str); 2] = [("BRA", "ADM2"), ("CAN", "ADM2")];

pub fn choose_level(
    units: &BTreeMap<&str, u64>,
    provinces: u64,
    over: Option<&str>,
) -> Option<&'static str> {
    if let Some(o) = over {
        return LEVELS
            .into_iter()
            .find(|l| *l == o && units.contains_key(l));
    }
    let ratios: Vec<(&'static str, f64)> = LEVELS
        .into_iter()
        .filter_map(|l| Some((l, *units.get(l)? as f64 / provinces as f64)))
        .collect();
    for (lo, hi) in [(GOOD_RATIO, MAX_RATIO), (MIN_RATIO, GOOD_RATIO)] {
        for &(level, r) in &ratios {
            if lo <= r && r <= hi {
                return Some(level);
            }
        }
    }
    None
}

/// A country's boundary file in the lock.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LockEntry {
    pub iso: String,
    pub level: String,
    /// The file's name in the cache.
    pub name: String,
}

/// The lock's files, in its order; none without a lock.
pub fn entries(root: &Path) -> Result<Vec<LockEntry>, String> {
    let lock = root.join(CONFIG_DIR).join(LOCK);
    if !lock.exists() {
        return Ok(vec![]);
    }
    let t = read_table(&lock)?;
    Ok(t.get("country")
        .and_then(toml::Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(toml::Value::as_table)
        .map(|c| {
            let text = |k: &str| c.get(k).and_then(toml::Value::as_str).unwrap_or_default();
            LockEntry {
                iso: text("iso").to_owned(),
                level: text("level").to_owned(),
                name: format!("geoboundaries/{}-{}.geojson", text("iso"), text("level")),
            }
        })
        .collect())
}

/// What the metadata API says of one country at one level.
pub type Meta = BTreeMap<String, Value>;

/// A string or an integer as text; anything else is an error.
fn text(v: &Value) -> Result<String, String> {
    match v {
        Value::String(s) => Ok(s.clone()),
        Value::Number(n) if n.is_i64() || n.is_u64() => Ok(n.to_string()),
        v => Err(format!("expected a string or an integer, got {v}")),
    }
}

/// `json.dumps` of a string: quoted, non-ASCII escaped as `\uXXXX`.
fn quoted(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            c if c.is_ascii() && !c.is_ascii_control() => out.push(c),
            c => {
                let mut units = [0u16; 2];
                for u in c.encode_utf16(&mut units) {
                    out.push_str(&format!("\\u{u:04x}"));
                }
            }
        }
    }
    out.push('"');
    out
}

/// The lock file for `meta` (level, then ISO code, to the API's record) and the admin-1 region
/// count per country; `fetch` returns the cached path of each chosen file.
pub fn lock_text(
    meta: &BTreeMap<&str, BTreeMap<String, Meta>>,
    per_country: &BTreeMap<String, u64>,
    mut fetch: impl FnMut(&Entry) -> Result<PathBuf, String>,
) -> Result<String, String> {
    let mut lines: Vec<String> = vec![
        "# Generated by `ceteris pack record-counties` (ADR 0009). One geoBoundaries gbOpen".into(),
        "# file per country at the level choose_level picks; licences are per file.".into(),
        String::new(),
    ];
    let field = |r: &Meta, k: &str| -> Result<String, String> {
        text(r.get(k).ok_or(format!("no {k}"))?).map_err(|e| format!("{k}: {e}"))
    };
    for (iso, &n) in per_country {
        let mut units = BTreeMap::new();
        for level in LEVELS {
            if let Some(r) = meta.get(level).and_then(|m| m.get(iso)) {
                let count = field(r, "admUnitCount").map_err(|e| format!("{iso} {level} {e}"))?;
                let count = count
                    .parse::<u64>()
                    .map_err(|e| format!("{iso} {level} admUnitCount {count}: {e}"))?;
                units.insert(level, count);
            }
        }
        let over = OVERRIDES.iter().find(|(c, _)| c == iso).map(|(_, l)| *l);
        let Some(level) = choose_level(&units, n, over) else {
            continue;
        };
        let r = &meta[level][iso];
        let entry = Entry {
            source: "geoboundaries".into(),
            name: format!("geoboundaries/{iso}-{level}.geojson"),
            sha256: None,
            bytes: None,
            url: field(r, "simplifiedGeometryGeoJSON")?,
            optional: false,
            manual: false,
        };
        let path = fetch(&entry)?;
        let (sha256, bytes) = digest(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let licence = field(r, "boundaryLicense")?;
        lines.extend([
            "[[country]]".into(),
            format!("iso = \"{iso}\""),
            format!("level = \"{level}\""),
            format!("units = {}", units[level]),
            format!("year = \"{}\"", field(r, "boundaryYearRepresented")?),
            format!("licence = {}", quoted(&licence)),
            format!("boundary_id = \"{}\"", field(r, "boundaryID")?),
            format!("url = \"{}\"", entry.url),
            format!("sha256 = \"{sha256}\""),
            format!("bytes = {bytes}"),
            String::new(),
        ]);
    }
    Ok(lines.join("\n"))
}

/// Admin-1 regions per current country, excluded countries left out.
pub fn regions_per_country(admin1: &Path) -> Result<BTreeMap<String, u64>, String> {
    let exclude = super::provinces::borders()?.exclude;
    let mut out = BTreeMap::new();
    for [code] in Dbf::from_zip(admin1)?.select(["adm0_a3"])? {
        let code = code.unwrap_or_default();
        if !exclude.contains(code) {
            *out.entry(code.to_owned()).or_insert(0) += 1;
        }
    }
    Ok(out)
}

fn get_json(url: &str) -> Result<Value, String> {
    reqwest::blocking::Client::builder()
        .user_agent("ceteris-packs")
        .timeout(std::time::Duration::from_secs(120))
        .build()
        .and_then(|c| c.get(url).send())
        .and_then(|r| r.error_for_status())
        .and_then(|r| r.bytes())
        .map_err(|e| format!("{url}: {e}"))
        .and_then(|b| serde_json::from_slice(&b).map_err(|e| format!("{url}: {e}")))
}

/// `pack record-counties`: queries the API, downloads the chosen files into the cache and
/// rewrites the lock.
pub fn record(root: &Path) -> Result<(), String> {
    let mut meta = BTreeMap::new();
    for level in LEVELS {
        let url = API.replace("{level}", level);
        let rows = get_json(&url)?;
        let rows = rows.as_array().ok_or(format!("{url}: not a list"))?;
        let by_iso: BTreeMap<String, Meta> = rows
            .iter()
            .filter_map(|r| {
                let r = r.as_object()?;
                let iso = r.get("boundaryISO")?.as_str()?.to_owned();
                Some((iso, r.iter().map(|(k, v)| (k.clone(), v.clone())).collect()))
            })
            .collect();
        meta.insert(level, by_iso);
    }
    let cache = root.join(fetch::CACHE_DIR);
    let admin1 = cache.join(crate::read::natural_earth::ADMIN1);
    let text = lock_text(&meta, &regions_per_country(&admin1)?, |e| {
        fetch::fetch(e, &cache).map_err(|e| e.to_string())
    })?;
    let lock = root.join(CONFIG_DIR).join(LOCK);
    std::fs::write(&lock, text).map_err(|e| format!("{}: {e}", lock.display()))
}

#[cfg(feature = "geos")]
pub use clip::{Clipped, County, assign, clip, load};

#[cfg(feature = "geos")]
mod clip {
    use geo::Geometry;
    use geos::{Geom, Geometry as Geos};
    use rstar::{AABB, RTree, RTreeObject};

    use super::entries;
    use crate::geo::overlay::{
        area, from_geo, intersection, is_empty, make_valid, polygonal, to_multipolygon,
    };
    use crate::geo::provinces::Province;
    use crate::geo::sphere::{anchor, area_km2};
    use crate::read::geojson;

    pub struct County {
        pub iso: String,
        pub level: String,
        pub name: String,
        pub geom: Geos,
        pub lon: f64,
        pub lat: f64,
    }

    /// Every county of the lock's cached files, repaired, its lines and points dropped; empty
    /// ones left out.
    pub fn load(root: &std::path::Path) -> Result<Vec<County>, String> {
        let cache = root.join(crate::fetch::CACHE_DIR);
        let mut out = Vec::new();
        for e in entries(root)? {
            for (name, g) in geojson::features(&cache.join(&e.name), "shapeName")? {
                let Some(g) = g else {
                    continue;
                };
                let g = polygonal(&make_valid(&from_geo(&g)?)?)?;
                if !is_empty(&g)? {
                    out.push(County {
                        iso: e.iso.clone(),
                        level: e.level.clone(),
                        name: name.unwrap_or_default(),
                        geom: g,
                        lon: 0.0,
                        lat: 0.0,
                    });
                }
            }
        }
        Ok(out)
    }

    struct Boxed(usize, AABB<[f64; 2]>);

    impl RTreeObject for Boxed {
        type Envelope = AABB<[f64; 2]>;
        fn envelope(&self) -> Self::Envelope {
            self.1
        }
    }

    fn envelope(g: &impl Geom) -> Result<AABB<[f64; 2]>, String> {
        let f = |r: geos::GResult<f64>| r.map_err(|e| e.to_string());
        Ok(AABB::from_corners(
            [f(g.get_x_min())?, f(g.get_y_min())?],
            [f(g.get_x_max())?, f(g.get_y_max())?],
        ))
    }

    /// Province index each county overlaps most (by planar area) among provinces of its
    /// country, ties to the lower index, or None. `countries[j]` holds the codes province j
    /// answers to (current and 2000), so Crimea's units, Ukrainian in geoBoundaries, still find
    /// Crimea.
    pub fn assign(
        counties: &[County],
        geoms: &[Geometry],
        countries: &[[&str; 2]],
    ) -> Result<Vec<Option<usize>>, String> {
        let pg = geoms.iter().map(from_geo).collect::<Result<Vec<_>, _>>()?;
        let tree = RTree::bulk_load(
            pg.iter()
                .enumerate()
                .map(|(i, g)| Ok(Boxed(i, envelope(g)?)))
                .collect::<Result<Vec<_>, String>>()?,
        );
        let mut out = Vec::with_capacity(counties.len());
        for c in counties {
            let prepared = c.geom.to_prepared_geom().map_err(|e| e.to_string())?;
            let mut best: Option<(usize, f64)> = None;
            for b in tree.locate_in_envelope_intersecting(&envelope(&c.geom)?) {
                let p = b.0;
                if !countries[p].contains(&c.iso.as_str())
                    || !prepared.intersects(&pg[p]).map_err(|e| e.to_string())?
                {
                    continue;
                }
                let a = area(&intersection(&c.geom, &pg[p])?)?;
                let better = match best {
                    None => a > 0.0,
                    Some((q, b)) => a > b || (a == b && p < q),
                };
                if better {
                    best = Some((p, a));
                }
            }
            out.push(best.map(|(p, _)| p));
        }
        Ok(out)
    }

    /// Counties each clipped to the province it overlaps most, ordered by province (stable),
    /// with their anchors; the misfit between the sources over counties that fit a province,
    /// as the summed areas of those counties whole and clipped; and how many counties overlap
    /// no province of their country.
    pub struct Clipped {
        pub province: Vec<u32>,
        pub counties: Vec<County>,
        pub fits: f64,
        pub fits_inside: f64,
        pub unassigned: usize,
    }

    pub fn clip(
        units: &[County],
        provinces: &[Province],
        split_area_km2: f64,
    ) -> Result<Clipped, String> {
        let geoms: Vec<Geometry> = provinces.iter().map(|p| p.geom.clone()).collect();
        let countries: Vec<[&str; 2]> = provinces
            .iter()
            .map(|p| [p.country.as_str(), p.country_now.as_str()])
            .collect();
        let home = assign(units, &geoms, &countries)?;
        let unassigned = home.iter().filter(|h| h.is_none()).count();
        let pg = geoms.iter().map(from_geo).collect::<Result<Vec<_>, _>>()?;
        let (mut fits, mut fits_inside) = (0.0, 0.0);
        let mut clipped = Vec::new();
        for (c, h) in units.iter().zip(home) {
            let Some(h) = h else {
                continue;
            };
            let piece = polygonal(&intersection(&c.geom, &pg[h])?)?;
            let whole = area_km2(&to_multipolygon(&c.geom)?);
            if whole <= split_area_km2 / 2.0 {
                fits += whole;
                fits_inside += area_km2(&to_multipolygon(&piece)?);
            }
            if !is_empty(&piece)? {
                let h = u32::try_from(h).map_err(|e| e.to_string())?;
                clipped.push((
                    h,
                    County {
                        iso: c.iso.clone(),
                        level: c.level.clone(),
                        name: c.name.clone(),
                        geom: piece,
                        lon: 0.0,
                        lat: 0.0,
                    },
                ));
            }
        }
        clipped.sort_by_key(|(h, _)| *h);
        let (province, mut counties): (Vec<u32>, Vec<County>) = clipped.into_iter().unzip();
        for c in &mut counties {
            (c.lon, c.lat) = anchor(&to_multipolygon(&c.geom)?).ok_or("a county without parts")?;
        }
        Ok(Clipped {
            province,
            counties,
            fits,
            fits_inside,
            unassigned,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn county_level_prefers_the_coarsest_level_in_range() {
        let u = |pairs: &[(&'static str, u64)]| pairs.iter().copied().collect::<BTreeMap<_, _>>();
        assert_eq!(
            choose_level(&u(&[("ADM2", 96), ("ADM3", 320)]), 101, None),
            Some("ADM3")
        );
        assert_eq!(choose_level(&u(&[("ADM2", 428)]), 16, None), Some("ADM2"));
        assert_eq!(
            choose_level(&u(&[("ADM2", 52), ("ADM3", 8205)]), 52, None),
            None
        );
        assert_eq!(choose_level(&u(&[("ADM2", 25)]), 15, None), Some("ADM2"));
        assert_eq!(
            choose_level(&u(&[("ADM2", 76), ("ADM3", 5162)]), 13, Some("ADM2")),
            Some("ADM2")
        );
    }

    fn meta_of(level: &'static str, iso: &str, units: Value) -> (&'static str, String, Meta) {
        let record: Meta = [
            ("admUnitCount", units),
            (
                "simplifiedGeometryGeoJSON",
                Value::from(format!("https://x/{iso}-{level}")),
            ),
            ("boundaryLicense", Value::from("Public Domain")),
            ("boundaryYearRepresented", Value::from(2014)),
            ("boundaryID", Value::from(format!("{iso}-{level}-1"))),
        ]
        .into_iter()
        .map(|(k, v)| (k.to_owned(), v))
        .collect();
        (level, iso.to_owned(), record)
    }

    fn lock(
        rows: Vec<(&'static str, String, Meta)>,
        per_country: &[(&str, u64)],
    ) -> Result<String, String> {
        let dir = tempfile::tempdir().unwrap();
        let file = dir.path().join("f.geojson");
        std::fs::write(&file, "{}").unwrap();
        let mut meta: BTreeMap<&str, BTreeMap<String, Meta>> = BTreeMap::new();
        for (level, iso, r) in rows {
            meta.entry(level).or_default().insert(iso, r);
        }
        let per: BTreeMap<String, u64> = per_country
            .iter()
            .map(|(c, n)| ((*c).to_owned(), *n))
            .collect();
        lock_text(&meta, &per, |_| Ok(file.clone()))
    }

    #[test]
    fn the_lock_takes_the_level_choose_level_picks_and_skips_countries_without_one() {
        let text = lock(
            vec![
                meta_of("ADM2", "AAA", Value::from("96")),
                meta_of("ADM3", "AAA", Value::from(320)),
                meta_of("ADM2", "BBB", Value::from(52)),
                meta_of("ADM3", "BBB", Value::from("8205")),
            ],
            &[("AAA", 101), ("BBB", 52), ("CCC", 7)],
        )
        .unwrap();
        let body: Vec<&str> = text.lines().skip(3).collect();
        assert_eq!(
            body[..5],
            [
                "[[country]]",
                "iso = \"AAA\"",
                "level = \"ADM3\"",
                "units = 320",
                "year = \"2014\""
            ]
        );
        assert!(!text.contains("BBB") && !text.contains("CCC"));
        assert_eq!(text.matches("[[country]]").count(), 1);
    }

    #[test]
    fn unit_counts_must_be_integers() {
        for bad in [Value::from(96.0), Value::Null] {
            let err = lock(vec![meta_of("ADM2", "AAA", bad)], &[("AAA", 10)]).unwrap_err();
            assert!(err.contains("admUnitCount"), "{err}");
        }
    }

    #[test]
    fn licences_are_written_as_json_dumps_writes_them() {
        assert_eq!(quoted("Public Domain"), "\"Public Domain\"");
        assert_eq!(
            quoted("CC BY 4.0 \"x\" é"),
            "\"CC BY 4.0 \\\"x\\\" \\u00e9\""
        );
        assert_eq!(quoted("\u{1F600}"), "\"\\ud83d\\ude00\"");
    }
}
